"""Разбор введённой строки на команду и аргументы."""


def parse_line(line):
    """Разделяет строку по пробельным символам.

    Возвращает пару (команда, список аргументов). Для пустой строки
    команда равна None.
    """
    tokens = line.split()
    if not tokens:
        return None, []
    return tokens[0], tokens[1:]
